CREATE FUNCTION miniupwork.guard_review()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE parties RECORD;
BEGIN
    SELECT c.status, j.client_id, p.freelancer_id INTO parties
    FROM miniupwork.contract c JOIN miniupwork.proposal p USING (proposal_id)
    JOIN miniupwork.job j USING (job_id) WHERE c.contract_id = NEW.contract_id FOR SHARE OF c;
    IF NOT FOUND OR parties.status <> 'COMPLETED' OR NOT (
        (NEW.reviewer_id, NEW.reviewee_id) = (parties.client_id, parties.freelancer_id)
        OR (NEW.reviewer_id, NEW.reviewee_id) = (parties.freelancer_id, parties.client_id)
    ) THEN
        RAISE EXCEPTION 'Only the two parties of a completed contract may review each other' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER review_guard BEFORE INSERT ON miniupwork.review FOR EACH ROW EXECUTE FUNCTION miniupwork.guard_review();

