ALTER TABLE miniupwork.app_user ADD COLUMN username VARCHAR(32) NOT NULL
    UNIQUE CHECK (username ~ '^[a-z][a-z0-9_]{2,31}$');

CREATE TABLE miniupwork.app_session (
    token_digest BYTEA PRIMARY KEY CHECK (octet_length(token_digest) = 32),
    user_id BIGINT NOT NULL REFERENCES miniupwork.app_user(user_id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX app_session_expiry ON miniupwork.app_session (expires_at);

CREATE TABLE miniupwork.contract (
    contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id BIGINT NOT NULL UNIQUE REFERENCES miniupwork.proposal(proposal_id) ON DELETE RESTRICT,
    contract_type TEXT NOT NULL CHECK (contract_type IN ('FIXED_PRICE', 'HOURLY')),
    status TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'COMPLETED', 'TERMINATED')),
    start_date DATE NOT NULL,
    end_date DATE,
    CHECK ((end_date IS NOT NULL) = (status IN ('COMPLETED', 'TERMINATED'))),
    CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE TABLE miniupwork.fixed_price_contract (
    contract_id BIGINT PRIMARY KEY REFERENCES miniupwork.contract(contract_id) ON DELETE RESTRICT,
    agreed_amount NUMERIC(12,2) NOT NULL CHECK (agreed_amount > 0 AND agreed_amount <> 'NaN'::numeric)
);
CREATE TABLE miniupwork.hourly_contract (
    contract_id BIGINT PRIMARY KEY REFERENCES miniupwork.contract(contract_id) ON DELETE RESTRICT,
    hourly_rate NUMERIC(12,2) NOT NULL CHECK (hourly_rate > 0 AND hourly_rate <> 'NaN'::numeric),
    weekly_limit SMALLINT NOT NULL CHECK (weekly_limit BETWEEN 1 AND 168)
);
CREATE TABLE miniupwork.milestone (
    milestone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.fixed_price_contract(contract_id) ON DELETE RESTRICT,
    sequence_no SMALLINT NOT NULL CHECK (sequence_no > 0),
    title TEXT NOT NULL CHECK (btrim(title) <> ''),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    due_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'FUNDED', 'SUBMITTED', 'APPROVED', 'RELEASED', 'CANCELLED', 'REFUNDED')),
    UNIQUE (contract_id, sequence_no)
);
CREATE TABLE miniupwork.escrow_funding (
    funding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    milestone_id BIGINT NOT NULL REFERENCES miniupwork.milestone(milestone_id) ON DELETE RESTRICT,
    funded_amount NUMERIC(12,2) NOT NULL CHECK (funded_amount > 0 AND funded_amount <> 'NaN'::numeric),
    funded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status TEXT NOT NULL DEFAULT 'FUNDED' CHECK (status IN ('FUNDED', 'RELEASED', 'REFUNDED'))
);
CREATE UNIQUE INDEX one_active_funding ON miniupwork.escrow_funding(milestone_id) WHERE status = 'FUNDED';

CREATE TABLE miniupwork.weekly_invoice (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.hourly_contract(contract_id) ON DELETE RESTRICT,
    period_start DATE NOT NULL CHECK (extract(isodow FROM period_start) = 1),
    period_end DATE GENERATED ALWAYS AS (period_start + 7) STORED,
    status TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ISSUED', 'APPROVED', 'DISPUTED', 'PAID')),
    UNIQUE (contract_id, period_start),
    UNIQUE (invoice_id, contract_id)
);
CREATE TABLE miniupwork.time_entry (
    entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.hourly_contract(contract_id) ON DELETE RESTRICT,
    invoice_id BIGINT,
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    description TEXT NOT NULL CHECK (btrim(description) <> ''),
    CHECK (start_at < end_at),
    FOREIGN KEY (invoice_id, contract_id) REFERENCES miniupwork.weekly_invoice(invoice_id, contract_id)
);
CREATE INDEX time_entry_by_contract ON miniupwork.time_entry(contract_id, start_at);
CREATE INDEX time_entry_by_invoice ON miniupwork.time_entry(invoice_id);

CREATE TABLE miniupwork.payment_transaction (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.contract(contract_id) ON DELETE RESTRICT,
    payer_id BIGINT NOT NULL REFERENCES miniupwork.app_user(user_id) ON DELETE RESTRICT,
    payee_id BIGINT NOT NULL REFERENCES miniupwork.app_user(user_id) ON DELETE RESTRICT,
    escrow_funding_id BIGINT REFERENCES miniupwork.escrow_funding(funding_id) ON DELETE RESTRICT,
    invoice_id BIGINT REFERENCES miniupwork.weekly_invoice(invoice_id) ON DELETE RESTRICT,
    original_payment_id BIGINT UNIQUE REFERENCES miniupwork.payment_transaction(payment_id) ON DELETE RESTRICT,
    transaction_type TEXT NOT NULL CHECK (transaction_type IN ('ESCROW_RELEASE', 'HOURLY_CHARGE', 'REVERSAL')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    currency_code CHAR(3) NOT NULL DEFAULT 'USD' CHECK (currency_code = 'USD'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (payer_id <> payee_id),
    CHECK ((escrow_funding_id IS NULL) <> (invoice_id IS NULL)),
    CHECK ((transaction_type = 'REVERSAL') = (original_payment_id IS NOT NULL)),
    CHECK (transaction_type = 'REVERSAL' OR (transaction_type = 'ESCROW_RELEASE') = (escrow_funding_id IS NOT NULL))
);
CREATE UNIQUE INDEX one_release_per_funding ON miniupwork.payment_transaction(escrow_funding_id) WHERE transaction_type = 'ESCROW_RELEASE';
CREATE UNIQUE INDEX one_release_per_invoice ON miniupwork.payment_transaction(invoice_id) WHERE transaction_type = 'HOURLY_CHARGE';
CREATE INDEX payments_by_contract ON miniupwork.payment_transaction(contract_id, payment_id);

CREATE TABLE miniupwork.review (
