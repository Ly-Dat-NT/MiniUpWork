CREATE VIEW miniupwork.rating_summary AS
SELECT u.user_id, COUNT(r.review_id) AS review_count,
       COALESCE(SUM(r.rating), 0) AS rating_sum, ROUND(AVG(r.rating), 2) AS avg_rating
FROM miniupwork.app_user AS u LEFT JOIN miniupwork.review AS r ON r.reviewee_id = u.user_id
GROUP BY u.user_id;

CREATE FUNCTION miniupwork.invoice_total(target BIGINT)
RETURNS TABLE(hours NUMERIC, amount NUMERIC) LANGUAGE sql STABLE AS $$
    SELECT ROUND(SUM(EXTRACT(epoch FROM (e.end_at - e.start_at))) / 3600.0, 2),
           ROUND(SUM(EXTRACT(epoch FROM (e.end_at - e.start_at))) * h.hourly_rate / 3600.0, 2)
    FROM miniupwork.weekly_invoice AS i
    JOIN miniupwork.hourly_contract AS h USING (contract_id)
    JOIN miniupwork.time_entry AS e USING (invoice_id)
    WHERE i.invoice_id = target
    GROUP BY h.hourly_rate;
$$;

CREATE FUNCTION miniupwork.guard_contract()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE job_kind TEXT; accepted TEXT; planned NUMERIC; agreed NUMERIC;
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT j.job_type, p.status INTO job_kind, accepted
        FROM miniupwork.proposal p JOIN miniupwork.job j USING (job_id)
        WHERE p.proposal_id = NEW.proposal_id FOR SHARE OF p;
        IF accepted IS DISTINCT FROM 'ACCEPTED' OR job_kind IS DISTINCT FROM NEW.contract_type
           OR NEW.status <> 'DRAFT' THEN
            RAISE EXCEPTION 'Contract needs an accepted proposal of the same type and starts as DRAFT'
                USING ERRCODE = '23514', CONSTRAINT = 'contract_origin';
        END IF;
        RETURN NEW;
    END IF;
    IF (NEW.contract_id, NEW.proposal_id, NEW.contract_type, NEW.start_date)
       IS DISTINCT FROM (OLD.contract_id, OLD.proposal_id, OLD.contract_type, OLD.start_date) THEN
        RAISE EXCEPTION 'Contract origin is immutable' USING ERRCODE = '23514';
    END IF;
    IF NEW.status = OLD.status THEN
        IF NEW.end_date IS DISTINCT FROM OLD.end_date THEN
            RAISE EXCEPTION 'End date changes only with closure' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF NOT ((OLD.status = 'DRAFT' AND NEW.status IN ('ACTIVE', 'TERMINATED'))
        OR (OLD.status = 'ACTIVE' AND NEW.status IN ('PAUSED', 'COMPLETED', 'TERMINATED'))
        OR (OLD.status = 'PAUSED' AND NEW.status IN ('ACTIVE', 'TERMINATED'))) THEN
        RAISE EXCEPTION 'Invalid contract transition' USING ERRCODE = '23514';
    END IF;
    IF NEW.status = 'ACTIVE' AND NEW.contract_type = 'FIXED_PRICE' THEN
        SELECT agreed_amount INTO agreed FROM miniupwork.fixed_price_contract WHERE contract_id = NEW.contract_id;
        SELECT SUM(amount) INTO planned FROM miniupwork.milestone WHERE contract_id = NEW.contract_id;
        IF planned IS NULL OR planned IS DISTINCT FROM agreed THEN
            RAISE EXCEPTION 'Milestones must add up to the agreed amount' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF NEW.status = 'COMPLETED' AND (
        EXISTS (SELECT 1 FROM miniupwork.milestone WHERE contract_id = NEW.contract_id AND status <> 'RELEASED')
        OR EXISTS (SELECT 1 FROM miniupwork.weekly_invoice WHERE contract_id = NEW.contract_id AND status <> 'PAID')
        OR EXISTS (SELECT 1 FROM miniupwork.time_entry WHERE contract_id = NEW.contract_id AND invoice_id IS NULL)
    ) THEN
        RAISE EXCEPTION 'Settle all work before completion' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER contract_guard BEFORE INSERT OR UPDATE ON miniupwork.contract
FOR EACH ROW EXECUTE FUNCTION miniupwork.guard_contract();

CREATE FUNCTION miniupwork.check_contract_subtype()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE target BIGINT; kind TEXT; fixed_present BOOLEAN; hourly_present BOOLEAN;
BEGIN
    target := CASE WHEN TG_OP = 'DELETE' THEN OLD.contract_id ELSE NEW.contract_id END;
    SELECT contract_type INTO kind FROM miniupwork.contract WHERE contract_id = target;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT EXISTS (SELECT 1 FROM miniupwork.fixed_price_contract WHERE contract_id = target),
           EXISTS (SELECT 1 FROM miniupwork.hourly_contract WHERE contract_id = target)
    INTO fixed_present, hourly_present;
    IF fixed_present <> (kind = 'FIXED_PRICE') OR hourly_present <> (kind = 'HOURLY') THEN
        RAISE EXCEPTION 'Contract requires exactly one matching pricing subtype' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER contract_subtype AFTER INSERT OR UPDATE ON miniupwork.contract
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_contract_subtype();
CREATE CONSTRAINT TRIGGER fixed_contract_subtype AFTER INSERT OR UPDATE OR DELETE ON miniupwork.fixed_price_contract
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_contract_subtype();
CREATE CONSTRAINT TRIGGER hourly_contract_subtype AFTER INSERT OR UPDATE OR DELETE ON miniupwork.hourly_contract
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_contract_subtype();
CREATE TRIGGER fixed_contract_key BEFORE UPDATE ON miniupwork.fixed_price_contract
